// Bakes ./data/*.csv into src/baked-data.js so the game works offline and
// whenever the Google Sheet can't be reached. Run after editing the CSVs.
const fs = require('fs'), path = require('path');
const D = require('../src/data.js');
const dir = path.join(__dirname, '..', 'data');
const tables = {};
D.TABS.forEach(t => {
  const p = path.join(dir, t + '.csv');
  if (fs.existsSync(p)) tables[t] = fs.readFileSync(p, 'utf8');
  else if (D.REQUIRED_TABS.includes(t)) { console.error(`Missing data/${t}.csv`); process.exit(1); }
});
const r = D.compileData(tables);
if (r.errors.length) { console.error('Data errors:\n- ' + r.errors.join('\n- ')); process.exit(1); }
fs.writeFileSync(path.join(__dirname, '..', 'src', 'baked-data.js'),
  '/* Generated by tools/bake.js from data/*.csv. Do not edit by hand. */\nwindow.CB_BAKED_TABLES = ' + JSON.stringify(tables, null, 1) + ';\n');
if (r.warnings.length) console.warn('Warnings:\n- ' + r.warnings.join('\n- '));
console.log(`Baked ${r.data.cardList.length} cards, ${r.data.styleList.length} styles, ${r.data.opponents.length} opponents, ${Object.keys(r.data.cutins).length} cut-in fighters, ${r.data.fighterList.length} custom fighters.`);
